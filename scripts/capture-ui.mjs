import { chromium } from "@playwright/test";
import { mkdir } from "node:fs/promises";
const base=process.env.PLAYWRIGHT_BASE_URL||"http://localhost:3000";
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||undefined});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
page.on("console",message=>{if(message.type()==="error")errors.push(message.text());});
await page.addInitScript(()=>localStorage.setItem("flightguard-preferences-v1",JSON.stringify({state:{mode:"demo",region:"central-europe"},version:0})));
await mkdir("docs/screenshots",{recursive:true});
await page.goto(base,{waitUntil:"domcontentloaded"});
await page.waitForSelector(".maplibregl-canvas");
await page.waitForSelector('[data-layers-ready="true"]');
await page.waitForTimeout(8000);
await page.screenshot({path:"docs/screenshots/map-demo-1440.png"});
console.log(JSON.stringify({page:"map",errors,aircraft:await page.locator(".stat-item strong").first().innerText(),weatherAvailable:await page.locator(".weather-summary").count(),canvas:await page.locator(".maplibregl-canvas").count()}));
await page.setViewportSize({width:1920,height:1080});
await page.waitForTimeout(1000);
await page.screenshot({path:"docs/screenshots/map-demo-1920.png"});
await page.setViewportSize({width:1366,height:768});
await page.waitForTimeout(1000);
await page.screenshot({path:"docs/screenshots/map-demo-1366.png"});
await page.setViewportSize({width:1440,height:900});
await page.goto(`${base}/compensation`,{waitUntil:"domcontentloaded"});
await page.getByLabel("Disruption reason").selectOption("airline");
await page.getByRole("button",{name:"Evaluate compensation"}).click();
await page.getByText("POTENTIALLY ELIGIBLE",{exact:true}).waitFor();
await page.screenshot({path:"docs/screenshots/compensation-1440.png"});
await page.setViewportSize({width:390,height:844});
await page.goto(base);
await page.waitForSelector(".maplibregl-canvas");
await page.waitForTimeout(2000);
await page.screenshot({path:"docs/screenshots/map-mobile.png"});
console.log(JSON.stringify({page:"final",errors}));
await browser.close();
