import { chromium } from "@playwright/test";
import { mkdir,writeFile } from "node:fs/promises";
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||undefined});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  page.setDefaultTimeout(60000);page.setDefaultNavigationTimeout(90000);
  const errors=[],requests=[],metrics={};
  page.on("pageerror",error=>{errors.push(error.message);console.log("Browser exception:",error.message);});
  page.on("request",request=>{if(request.url().includes("/api/"))requests.push(request.url());});
  await page.addInitScript(()=>localStorage.setItem("flightguard-preferences-v1",JSON.stringify({state:{mode:"demo",uiMode:"simple",region:"central-europe"},version:0})));
  const started=Date.now();
  await page.goto(process.env.PLAYWRIGHT_BASE_URL||"http://localhost:3000",{waitUntil:"domcontentloaded"});
  await page.getByRole("heading",{name:/EGLL.*LHR/}).waitFor();
  metrics.shellMs=Date.now()-started;
  await page.waitForSelector('[data-map-ready="true"]');
  metrics.mapMs=Date.now()-started;
  console.log("Simple ready",JSON.stringify({metrics,requests,errors}));
  await page.locator(".maplibregl-canvas").evaluate(node=>node.setAttribute("data-instance","original"));
  // Allow a completed tile render before recording the visual.
  await page.waitForTimeout(2500);
  await mkdir("docs/screenshots",{recursive:true});
  await page.screenshot({path:"docs/screenshots/map-simple-1440.png"});
  await page.getByRole("button",{name:"Advanced",exact:true}).click();
  await page.getByRole("button",{name:"Play recorded snapshots"}).waitFor();
  metrics.canvasPreserved=await page.locator(".maplibregl-canvas").getAttribute("data-instance")==="original";
  await page.getByRole("button",{name:"Map layers · L",exact:true}).click();
  await page.getByLabel("Airport cloud forecasts").check();
  await page.getByLabel("Airport wind forecasts").check();
  await page.getByLabel("Airport temperatures").check();
  await page.waitForTimeout(1000);
  metrics.weatherAirportsRequested=new Set(requests.filter(url=>/\/api\/airports\/[^/]+\/weather/.test(url)).map(url=>url.match(/\/airports\/([^/]+)\/weather/)[1])).size;
  await page.getByRole("button",{name:"Close map layers"}).click();
  await page.screenshot({path:"docs/screenshots/map-advanced-1440.png"});
  await page.getByRole("button",{name:"Simple",exact:true}).click();
  await page.getByRole("button",{name:/^Flights 128/}).click();
  metrics.renderedAircraftRows=await page.locator(".aircraft-list-row").count();
  await page.locator(".virtual-list").evaluate(node=>{node.scrollTop=node.scrollHeight;});
  await page.getByRole("button",{name:/DEMO128/}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole("button",{name:"Airports",exact:true}).click();
  await page.getByRole("button",{name:/EGLL.*LHR/}).click();
  await page.screenshot({path:"docs/screenshots/map-simple-mobile.png"});
  metrics.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  await page.setViewportSize({width:1440,height:900});
  await page.goto(`${process.env.PLAYWRIGHT_BASE_URL||"http://localhost:3000"}/compensation`,{waitUntil:"domcontentloaded"});
  await page.getByLabel("Disruption reason").selectOption("airline");
  await page.getByRole("button",{name:"Evaluate compensation"}).click();
  await page.getByText("POTENTIALLY ELIGIBLE",{exact:true}).waitFor();
  await page.screenshot({path:"docs/screenshots/compensation-ticket-1440.png"});
  await writeFile("docs/screenshots/loading-check.json",JSON.stringify({metrics,requests,errors},null,2));
  console.log(JSON.stringify({metrics,requests,errors}));
  if(errors.length||!metrics.canvasPreserved||metrics.mobileOverflow||metrics.weatherAirportsRequested>9)process.exitCode=1;
}finally{await browser.close();}
